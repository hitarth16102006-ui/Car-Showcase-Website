/* ================================================
   compare.js
   Backend-free "Compare Cars" system. Works just
   like wishlist.js: selected car ids live in
   localStorage (max 3 at a time) so the compare
   button state and the floating compare bar stay in
   sync across every page without a server.
   ================================================ */

var AUTOVERSE_COMPARE_KEY = 'autoverseCompare';
var AUTOVERSE_COMPARE_MAX = 3;

function getCompareIds() {
    try {
        var raw = localStorage.getItem(AUTOVERSE_COMPARE_KEY);
        return raw ? JSON.parse(raw) : [];
    } catch (error) {
        return [];
    }
}

function saveCompareIds(ids) {
    try {
        localStorage.setItem(AUTOVERSE_COMPARE_KEY, JSON.stringify(ids));
    } catch (error) {
        return;
    }
}

function isCarInCompare(carId) {
    return getCompareIds().indexOf(carId) !== -1;
}

function toggleCompare(carId) {
    var ids = getCompareIds();
    var index = ids.indexOf(carId);

    if (index === -1) {
        if (ids.length >= AUTOVERSE_COMPARE_MAX) {
            alert('You can compare up to ' + AUTOVERSE_COMPARE_MAX + ' cars at a time. Remove one first to add another.');
            return false;
        }

        ids.push(carId);
    } else {
        ids.splice(index, 1);
    }

    saveCompareIds(ids);
    refreshCompareUI();
    return ids.indexOf(carId) !== -1;
}

function compareButtonHTML(carId, extraClass) {
    var active = isCarInCompare(carId) ? ' active' : '';
    var cls = extraClass ? ' ' + extraClass : '';
    return (
        '<button type="button" class="compare-toggle' + active + cls + '" data-compare-id="' + carId + '" ' +
            'aria-label="Add to compare" aria-pressed="' + (active ? 'true' : 'false') + '" title="Add to compare">' +
            '<svg viewBox="0 0 24 24" width="16" height="16"><path d="M3 12h18M3 6h18M3 18h18"/></svg>' +
            '<span>Compare</span>' +
        '</button>'
    );
}

/* Delegated click handler - works no matter when the button markup
   was rendered (static HTML or generated by cars.js/details.js). */
document.addEventListener('click', function (event) {
    var btn = event.target.closest ? event.target.closest('.compare-toggle') : null;

    if (!btn) {
        return;
    }

    event.preventDefault();
    event.stopPropagation();

    var carId = btn.getAttribute('data-compare-id');

    if (!carId) {
        return;
    }

    var nowActive = toggleCompare(carId);

    document.querySelectorAll('.compare-toggle[data-compare-id="' + carId + '"]').forEach(function (el) {
        el.classList.toggle('active', nowActive);
        el.setAttribute('aria-pressed', nowActive ? 'true' : 'false');
    });
});

/* ---------- Floating compare bar (every page) ---------- */
function renderCompareBar() {
    var existing = document.getElementById('compareBar');
    var ids = getCompareIds();

    if (ids.length < 2) {
        if (existing) {
            existing.remove();
        }
        return;
    }

    if (typeof CARS === 'undefined') {
        return;
    }

    var cars = ids.map(function (id) { return getCarById(id); }).filter(Boolean);

    var bar = existing || document.createElement('div');
    bar.id = 'compareBar';
    bar.className = 'compare-bar';

    bar.innerHTML =
        '<div class="compare-bar-inner">' +
            '<div class="compare-bar-cars">' +
                cars.map(function (car) {
                    return (
                        '<div class="compare-bar-car">' +
                            '<span>' + car.brand + ' ' + car.name.replace(car.brand, '').trim() + '</span>' +
                            '<button type="button" class="compare-toggle active" data-compare-id="' + car.id + '" aria-label="Remove ' + car.name + ' from compare">&times;</button>' +
                        '</div>'
                    );
                }).join('') +
            '</div>' +
            '<a href="compare.html" class="btn compare-bar-btn">Compare (' + cars.length + ') <span class="arrow">&rarr;</span></a>' +
        '</div>';

    if (!existing) {
        document.body.appendChild(bar);
    }
}

function refreshCompareUI() {
    renderCompareBar();

    if (typeof renderComparePage === 'function') {
        renderComparePage();
    }
}

document.addEventListener('DOMContentLoaded', renderCompareBar);

