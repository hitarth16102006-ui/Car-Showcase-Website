/* ---------- Comparison table: highlight the best value in each row ----------
   The table is drawn by the compare page; this only reads it afterwards.
   Lower is better for price, 0-100 and weight; higher is better for the rest.
   Rows where every car has the same value are dimmed (.compare-same). */
function highlightCompareBest() {
    const rows = document.querySelectorAll('.compare-row');

    rows.forEach(row => {
        const labelEl = row.querySelector('.compare-row-label');
        const cells = Array.from(row.querySelectorAll('.compare-cell'));

        cells.forEach(cell => cell.classList.remove('compare-best'));
        row.classList.remove('compare-same');

        if (!labelEl || cells.length < 2) {
            return;
        }

        const texts = cells.map(cell => cell.textContent.trim());

        if (texts.every(text => text === texts[0])) {
            row.classList.add('compare-same');
            return;
        }

        const numbers = texts.map(text => {
            const match = text.replace(/,/g, '').match(/-?\d+(\.\d+)?/);
            return match ? parseFloat(match[0]) : NaN;
        });

        if (numbers.some(isNaN)) {
            return;
        }

        const lowerIsBetter = /price|0-100|accel|weight|sec/i.test(labelEl.textContent);
        const best = lowerIsBetter ? Math.min(...numbers) : Math.max(...numbers);

        numbers.forEach((value, index) => {
            if (value === best) {
                cells[index].classList.add('compare-best');
            }
        });
    });
}

if (typeof document !== 'undefined' && typeof MutationObserver !== 'undefined') {
    document.addEventListener('DOMContentLoaded', () => {
        const section = document.querySelector('.compare-section');

        if (!section) {
            return;
        }

        const observer = new MutationObserver(() => {
            /* stop watching while we change classes, then watch again */
            observer.disconnect();
            highlightCompareBest();
            observer.observe(section, { childList: true, subtree: true });
        });

        highlightCompareBest();
        observer.observe(section, { childList: true, subtree: true });
    });
}

